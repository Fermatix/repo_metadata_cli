def test_minified_single_line_is_autogen(tmp_path):
    f = tmp_path / "app.js"
    f.write_text("var a=1;" * 4000)  # 32 KB, one line
    assert _is_autogen_file(f, tmp_path, set()) is True


def test_long_average_line_is_autogen(tmp_path):
    f = tmp_path / "data.js"
    f.write_text("\n".join(["x" * 400] * 100))  # 100 lines, 400 B each
    assert _is_autogen_file(f, tmp_path, set()) is True


def test_normal_large_file_is_not_autogen(tmp_path):
    f = tmp_path / "big_module.py"
    f.write_text("\n".join(f"value_{i} = {i}" for i in range(2000)))  # ~30 KB
    assert _is_autogen_file(f, tmp_path, set()) is False


def test_small_file_skips_shape_check(tmp_path):
    f = tmp_path / "one_liner.js"
    f.write_text("var a=1;" * 100)  # 800 B single line — below the size floor
    assert _is_autogen_file(f, tmp_path, set()) is False



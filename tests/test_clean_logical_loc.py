def test_sql_dump_by_banner(tmp_path):
    f = tmp_path / "backup.sql"
    f.write_text("-- MySQL dump 10.13\nCREATE TABLE t (id INT);\n")
    assert _is_sql_dump(f) is True


def test_sql_dump_by_insert_rows(tmp_path):
    rows = "\n".join(f"INSERT INTO t VALUES ({i});" for i in range(60))
    f = tmp_path / "seed.sql"
    f.write_text("CREATE TABLE t (id INT);\n" + rows + "\n")
    assert _is_sql_dump(f) is True
    assert _is_autogen_file(f, tmp_path, set()) is True


def test_sql_migration_is_not_dump(tmp_path):
    f = tmp_path / "001_create_users.sql"
    f.write_text(
        "CREATE TABLE users (\n  id SERIAL PRIMARY KEY,\n  name TEXT\n);\n"
        "CREATE INDEX idx_users_name ON users (name);\n"
    )
    assert _is_sql_dump(f) is False
    assert _is_autogen_file(f, tmp_path, set()) is False



def _make_allowed_files() -> AllowedFiles:
    return AllowedFiles(AllowedFilesConfig(config_file=_TOML_PATH))


@pytest.fixture
def clean_repo(tmp_path):
    """Synthetic repo exercising every clean_logical_loc rule:

    src/main.py           — code, counted
    src/style.css         — markup counts as code, counted
    src/data.json         — non-code language, dropped
    res/layout/main.xml   — Android res XML, counted
    config/feed.xml       — plain XML, dropped
    db/backup.sql         — dump (banner), dropped
    bitrix/core.php       — CMS core dir, excluded by clean list only
    """
    repo = tmp_path / "repo"
    for d in ("src", "res/layout", "config", "db", "bitrix"):
        (repo / d).mkdir(parents=True)
    (repo / "src" / "main.py").write_text("\n".join(f"a_{i} = {i}" for i in range(10)) + "\n")
    (repo / "src" / "style.css").write_text(".cls {\n  color: red;\n}\n")
    (repo / "src" / "data.json").write_text('{\n  "k": 1\n}\n')
    (repo / "res" / "layout" / "main.xml").write_text("<LinearLayout>\n</LinearLayout>\n")
    (repo / "config" / "feed.xml").write_text("<items>\n<item/>\n</items>\n")
    (repo / "db" / "backup.sql").write_text("-- MySQL dump 10.13\nCREATE TABLE t (id INT);\n")
    (repo / "bitrix" / "core.php").write_text("<?php\n" + "\n".join(f"$b{i} = {i};" for i in range(50)) + "\n")
    run(["git", "init"], cwd=repo, check=True, capture_output=True)
    return repo


def test_clean_logical_loc_rules(clean_repo):
    settings = load_app_settings(_TOML_PATH)
    total = get_clean_logical_loc(
        clean_repo,
        exclude_dirs=list(settings.metrics.clean_scc_exclude_dirs),
        non_code_languages=set(settings.metrics.clean_non_code_languages),
    )
    # 10 (main.py) + 3 (style.css) + 2 (res XML); json/plain xml/sql dump/bitrix dropped
    assert total == 15


def test_clean_metric_vs_logical(clean_repo):
    settings = load_app_settings(_TOML_PATH)
    ctx = RepoContext(
        repo_path=clean_repo,
        settings=settings,
        tree_sitter=None,
        allowed_files=_make_allowed_files(),
    )
    clean = CleanLogicalLocMetric().compute(ctx)
    logical = LogicalLocMetric().compute(ctx)
    assert clean == 15
    # logical counts the CMS core, data json, plain XML and the SQL dump too
    assert clean < logical
